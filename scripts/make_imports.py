#!/usr/bin/env python3
"""Update the generated part of `blueprint/IMPORTS.md`: module -> Lean files -> imports,
declaration and `sorry` counts, and the module dependency graph (transitive reduction of the file
imports).  Only the text between the markers

    <!-- BEGIN GENERATED (scripts/make_imports.py) -->  ...  <!-- END GENERATED -->

is rewritten; the hand-written sections of IMPORTS.md (e.g. "Interface reconciliation") are kept.
Run from the repository root:  python3 scripts/make_imports.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
pkg = root / "FourierFrames"
BEGIN = "<!-- BEGIN GENERATED (scripts/make_imports.py) -->"
END = "<!-- END GENERATED -->"

MODULES = [  # (module, title, file prefixes relative to FourierFrames/)
    ("M00", "Definitions", ["Defs"]),
    ("M01", "Paley-Wiener toolkit", ["PW/"]),
    ("M02", "Hermite-Biehler, phases, H(E)", ["HB/"]),
    ("M03", "Theorem 1, necessity", ["Theorem1/Necessity"]),
    ("M04", "Theorem 1 sufficiency, Corollary 1", ["Theorem1/Sufficiency", "Theorem1/Main", "Corollary1"]),
    ("M05", "Landau's inequality", ["Landau"]),
    ("M06", "Logarithmic example", ["LogExample"]),
    ("M07", "Construction, perturbation, Corollary 2", ["Construction", "Perturbation", "Corollary2"]),
    ("M08", "Theorem 2 (i)", ["Theorem2i"]),
    ("M09", "Theorem 2 (ii) (+ uniform Lemma 3 estimate)", ["Theorem2ii", "Lemma3Uniform"]),
    ("M10", "Fourier frames", ["Frames"]),
    ("P1", "Paley-Wiener theorem", ["Cited/PaleyWiener"]),
    ("P2", "Duffin-Schaeffer, John-Nirenberg", ["Cited/DSPerturbation", "Cited/JohnNirenberg"]),
    ("P3", "de Branges D, E", ["Cited/DeBrangesDE"]),
    ("P4", "de Branges C, F (scaffold)", ["Cited/DeBrangesFC"]),
]


def rel(p):
    return str(p.relative_to(pkg))[:-5]


def module_of(r):
    for m, _, prefs in MODULES:
        for pr in prefs:
            if r == pr or r.startswith(pr.rstrip("/") + "/"):
                return m
    raise KeyError(r)


def strip_comments(s):
    out, i, depth = [], 0, 0
    while i < len(s):
        if s.startswith("/-", i):
            depth += 1; i += 2; continue
        if depth and s.startswith("-/", i):
            depth -= 1; i += 2; continue
        if not depth and s.startswith("--", i):
            j = s.find("\n", i); i = len(s) if j < 0 else j; continue
        if not depth:
            out.append(s[i])
        i += 1
    return "".join(out)


DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:private |protected |noncomputable )*"
                  r"(?:theorem|lemma|def|structure|class|instance|abbrev)\b", re.M)

info = {}
for p in sorted(pkg.rglob("*.lean")):
    r = rel(p)
    txt = p.read_text()
    code = strip_comments(txt)
    imps = [l.split()[-1] for l in txt.splitlines() if l.startswith(("import ", "public import "))]
    proj = [i.removeprefix("FourierFrames.").replace(".", "/") for i in imps if i.startswith("FourierFrames.")]
    other = [i for i in imps if not i.startswith("FourierFrames.")]
    info[r] = dict(mod=module_of(r), imports=proj, other=other,
                   decls=len(DECL.findall(code)), sorries=len(re.findall(r"\bsorry\b", code)))

edges = {m: set() for m, _, _ in MODULES}
for r, d in info.items():
    for i in d["imports"]:
        mi = module_of(i)
        if mi != d["mod"]:
            edges[d["mod"]].add(mi)


def reach(m, seen=None):
    seen = set() if seen is None else seen
    for n in edges[m]:
        if n not in seen:
            seen.add(n); reach(n, seen)
    return seen


reduced = {m: {n for n in es if not any(n in reach(k) for k in es if k != n)} for m, es in edges.items()}

L = [BEGIN, "",
     "Generated by `python3 scripts/make_imports.py` from the `import` lines of `FourierFrames/**/*.lean`.",
     "`decls` counts theorems, definitions, structures and instances; `sorry` counts the `sorry` tokens",
     "outside comments. `vendored/Mathlib` lists the non-project imports.", "",
     "### Files", "",
     "| module | file | decls | sorry | project imports | other imports |", "|---|---|---:|---:|---|---|"]
for m, title, _ in MODULES:
    for r in sorted(k for k, d in info.items() if d["mod"] == m):
        d = info[r]
        imps = ", ".join(f"`{i}`" for i in d["imports"]) or "—"
        oth = ", ".join(f"`{i}`" for i in d["other"] if i != "Mathlib") or ("Mathlib" if "Mathlib" in d["other"] else "—")
        L.append(f"| {m} | `{r}.lean` | {d['decls']} | {d['sorries']} | {imps} | {oth} |")
L += ["", "### Modules", "", "| module | content | files | decls | sorry | direct module dependencies |",
      "|---|---|---:|---:|---:|---|"]
for m, title, _ in MODULES:
    fs = [d for d in info.values() if d["mod"] == m]
    deps = ", ".join(sorted(reduced[m])) or "—"
    L.append(f"| {m} | {title} | {len(fs)} | {sum(d['decls'] for d in fs)} | "
             f"{sum(d['sorries'] for d in fs)} | {deps} |")
tot_d = sum(d["decls"] for d in info.values()); tot_s = sum(d["sorries"] for d in info.values())
L += ["", f"Total: {len(info)} files, {tot_d} declarations, {tot_s} `sorry`.", "",
      "### Module dependency graph (transitive reduction)", "", "```"]
for m, _, _ in MODULES:
    L.append(f"{m:4} <- {', '.join(sorted(reduced[m])) or '—'}")
L += ["```", "", "Full (transitive) dependencies:", "", "```"]
for m, _, _ in MODULES:
    L.append(f"{m:4} <- {', '.join(sorted(reach(m))) or '—'}")
L += ["```", "", END]
block = "\n".join(L)

path = root / "blueprint" / "IMPORTS.md"
if path.exists() and BEGIN in path.read_text():
    s = path.read_text()
    i, j = s.index(BEGIN), s.index(END) + len(END)
    s = s[:i] + block + s[j:]
else:
    s = "# Imports and interface reconciliation\n\n## Module graph (generated)\n\n" + block + "\n"
path.write_text(s)
print("\n".join(L[-30:]))
